console.log("SCHAGLK GAME 3D SCENE READY",scene);
JS
    cat > "$1/game.json" <<'JSON'
{
  "engine":"SCHAGLK",
  "type":"3D",
  "status":"prototype-ready",
  "assets":"assets",
  "source":"src"
}
JSON
}

create_pc() {
    mkdir -p "$1/src"
    cat > "$1/CMakeLists.txt" <<'CMAKE'
cmake_minimum_required(VERSION 3.10)
project(schaglk_pc)
set(CMAKE_CXX_STANDARD 17)
add_executable(schaglk_pc src/main.cpp)
CMAKE

    cat > "$1/src/main.cpp" <<'CPP'
#include <iostream>
int main() {
    std::cout << "SCHAGLK PC PROJECT READY" << std::endl;
    return 0;
}
CPP
}

create_native() {
    mkdir -p "$1/src"
    cat > "$1/src/main.c" <<'C'
#include <stdio.h>
int main(void) {
    puts("SCHAGLK NATIVE PROJECT READY");
    return 0;
}
C
}

TYPE="${1:-}"
NAME="${2:-}"

[ -n "$TYPE" ] || { usage; exit 1; }
[ -n "$NAME" ] || { usage; exit 1; }

NAME="$(safe_name "$NAME")"
TARGET="$OUT/$NAME"

rm -rf "$TARGET"
mkdir -p "$TARGET"

case "$TYPE" in
    web) create_web "$TARGET" ;;
    api) create_api "$TARGET" ;;
    python) create_python "$TARGET" ;;
    android) create_android "$TARGET" ;;
    game2d) create_game2d "$TARGET" ;;
    game3d) create_game3d "$TARGET" ;;
    pc) create_pc "$TARGET" ;;
    native) create_native "$TARGET" ;;
    *) usage; exit 1 ;;
esac

cat > "$TARGET/schaglk-project.json" <<JSON
{
  "name":"$NAME",
  "type":"$TYPE",
  "generatedBy":"SCHAGLK",
  "status":"generated"
}
JSON

echo "PROJECT_CREATED=$TARGET"
